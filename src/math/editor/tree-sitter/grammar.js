// Editing syntax, not mathematical evaluation. Control-sequence boundaries
// follow input/tex/TexScanner; groups remain present during error recovery.
module.exports = grammar({
  name: 'folia_tex',
  extras: $ => [/[\s\u00a0\u1680\u2000-\u200a\u2028\u2029\u202f\u205f\u3000\ufeff]/, $.comment],
  rules: {
    source_file: $ => repeat($._item),
    _item: $ => choice($.group, $.parenthesized, $.bracketed,
      $.left_right, $.environment, $.sized_delimiter, $.text,
      $.command, $.incomplete_command, $.number, $.identifier, $.operator, $.symbol),
    group: $ => seq('{', repeat($._item), '}'),
    parenthesized: $ => seq('(', repeat($._item), ')'),
    bracketed: $ => seq('[', repeat($._item), ']'),
    left_right: $ => seq(field('open', $.left_delimiter), repeat($._item), field('close', $.right_delimiter)),
    left_delimiter: $ => seq(field('modifier', '\\left'), field('delimiter', $.delimiter)),
    right_delimiter: $ => seq(field('modifier', '\\right'), field('delimiter', $.delimiter)),
    sized_delimiter: $ => seq(field('modifier', choice('\\middle', '\\big', '\\Big', '\\bigg', '\\Bigg',
      '\\bigl', '\\Bigl', '\\biggl', '\\Biggl', '\\bigr', '\\Bigr', '\\biggr', '\\Biggr',
      '\\bigm', '\\Bigm', '\\biggm', '\\Biggm')), field('delimiter', $.delimiter)),
    delimiter: $ => choice('(', ')', '[', ']', '{', '}', '|', '.', '<', '>', '/', $.command),
    environment: $ => seq(field('open', $.begin), repeat($._item), field('close', $.end)),
    begin: $ => seq(field('command', '\\begin'), field('name', $.environment_name)),
    end: $ => seq(field('command', '\\end'), field('name', $.environment_name)),
    environment_name: $ => seq('{', $.identifier, optional('*'), '}'),
    text: $ => seq(field('command', choice('\\text', '\\mbox', '\\hbox')), field('content', $.group)),
    command: $ => token(seq('\\', choice(/[A-Za-z]+/, /[^A-Za-z\r\n]/))),
    incomplete_command: $ => token('\\'),
    number: $ => /[0-9]+(?:\.[0-9]*)?/,
    identifier: $ => /[\p{L}\p{M}]+/u,
    operator: $ => /[+\-=<>\/*^_&:,;!|]/,
    symbol: $ => /[^\s\p{L}\p{M}0-9\\{}()\[\]%+\-=<>\/*^_&:,;!|]/u,
    comment: $ => token(seq('%', /[^\r\n]*/)),
  },
});
