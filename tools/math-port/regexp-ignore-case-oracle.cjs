function canonicalize(unit){
  const upper=String.fromCharCode(unit).toUpperCase();
  if(upper.length!==1)return unit;
  const mapped=upper.charCodeAt(0);
  // ECMAScript Canonicalize for non-u matching prevents non-ASCII units from
  // folding into ASCII. Surrogates are already identity-mapped by toUpperCase.
  return unit>=0x80&&mapped<0x80?unit:mapped;
}
