"""Serialize native TeX aliases from pinned, independently captured observations.

Capture reference data with tex-package-conformance.cjs first. This script uses
only Python's standard library and never executes JavaScript or native tests.
"""

import argparse
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
FIXTURE = ROOT / "tests/math/fixtures/packages/registry/aliases.json"
OUTPUT = ROOT / "src/math/input/tex/mediawiki_texvc/alias_data.inc"


def render() -> str:
    data = json.loads(FIXTURE.read_text(encoding="utf-8"))
    source = data["source"]
    digest = hashlib.sha256((ROOT / source["file"]).read_bytes()).hexdigest()
    if digest != source["sha256"] or source["version"] != "2.7.9":
        raise ValueError("Pinned mediawiki-texvc source differs from captured observations")
    rows = []
    seen = set()
    for item in data["aliases"]:
        name, replacement, count = item["name"], item["replacement"], item["argument_count"]
        if item["method"] != "Macro" or name in seen:
            raise ValueError("Invalid or duplicate captured TeX alias: " + name)
        if count is not None and (type(count) is not int or count < 0):
            raise ValueError("Invalid captured TeX alias argument count")
        seen.add(name)
        quote = lambda value: "u" + json.dumps(value, ensure_ascii=False)
        arguments = "std::u16string(" + quote(replacement) + ")"
        if count is not None:
            arguments += ", double(" + str(count) + ")"
        rows.append("Macro(" + quote(name) + ", MacroMethod{&BaseMethods::Macro}, {" + arguments + "}),")
    if not rows:
        raise ValueError("Captured TeX alias fixture is empty")
    return ("// Generated by tools/math-port/generate-texvc-aliases.py from MathJax 2.7.9.\n"
            "// Copyright (c) 2015-2020 The MathJax Consortium. Apache-2.0.\n" +
            "\n".join(rows) + "\n")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Fail if native alias data is stale")
    args = parser.parse_args()
    result = render()
    if args.check:
        if OUTPUT.read_text(encoding="utf-8") != result:
            raise SystemExit("Native TeX aliases are stale: run tools/math-port/generate-texvc-aliases.py")
    else:
        OUTPUT.write_text(result, encoding="utf-8", newline="\n")
    print("Native TeX alias data matches pinned observations")


if __name__ == "__main__":
    main()
